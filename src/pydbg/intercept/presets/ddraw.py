def decode_hresult(value: int) -> str:
    """Decode a DirectDraw HRESULT value to its name.

    Args:
        value: The HRESULT code (32-bit unsigned).

    Returns:
        The symbolic name if known, or a hex string if unknown.
    """
    # Mask to 32 bits for consistent lookup
    value = value & 0xFFFFFFFF
    return DDRAW_HRESULTS.get(value, f"0x{value:08X}")
